BEGIN;

CREATE TABLE IF NOT EXISTS contactos_whatsapp (
  id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  numero_compat         bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000) UNIQUE,
  canal_id              uuid NOT NULL REFERENCES canales_whatsapp(id) ON DELETE RESTRICT,
  nombre                text NOT NULL,
  telefono              text NOT NULL,
  telefono_normalizado  text NOT NULL,
  source_id             text NOT NULL,
  atributos             jsonb NOT NULL DEFAULT '{}'::jsonb,
  creado_en             timestamptz NOT NULL DEFAULT now(),
  actualizado_en        timestamptz NOT NULL DEFAULT now(),
  UNIQUE (canal_id, telefono_normalizado),
  UNIQUE (canal_id, source_id)
);

ALTER TABLE conversaciones
  ADD COLUMN IF NOT EXISTS numero_compat bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000),
  ADD COLUMN IF NOT EXISTS contacto_whatsapp_id uuid,
  ADD COLUMN IF NOT EXISTS atributos jsonb NOT NULL DEFAULT '{}'::jsonb;

CREATE UNIQUE INDEX IF NOT EXISTS conversaciones_numero_compat_key
  ON conversaciones(numero_compat);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'conversaciones_contacto_whatsapp_id_fkey'
      AND conrelid = 'conversaciones'::regclass
  ) THEN
    ALTER TABLE conversaciones
      ADD CONSTRAINT conversaciones_contacto_whatsapp_id_fkey
      FOREIGN KEY (contacto_whatsapp_id)
      REFERENCES contactos_whatsapp(id)
      ON DELETE SET NULL;
  END IF;
END $$;

ALTER TABLE conversaciones
  DROP CONSTRAINT IF EXISTS conversaciones_estado_check;

ALTER TABLE conversaciones
  ADD CONSTRAINT conversaciones_estado_check
  CHECK (estado IN ('abierta', 'pendiente', 'cerrada', 'resuelta', 'pospuesta'));

INSERT INTO contactos_whatsapp (
  canal_id,
  nombre,
  telefono,
  telefono_normalizado,
  source_id
)
SELECT
  canal_id,
  nombre_contacto,
  '+521' || right(regexp_replace(telefono_normalizado, '\D', '', 'g'), 10),
  right(regexp_replace(telefono_normalizado, '\D', '', 'g'), 10),
  '521' || right(regexp_replace(telefono_normalizado, '\D', '', 'g'), 10)
FROM conversaciones
WHERE length(regexp_replace(telefono_normalizado, '\D', '', 'g')) = 10
   OR regexp_replace(telefono_normalizado, '\D', '', 'g') ~ '^52[0-9]{10}$'
   OR regexp_replace(telefono_normalizado, '\D', '', 'g') ~ '^521[0-9]{10}$'
ON CONFLICT (canal_id, telefono_normalizado) DO NOTHING;

UPDATE conversaciones AS conversacion
SET contacto_whatsapp_id = contacto.id
FROM contactos_whatsapp AS contacto
WHERE conversacion.contacto_whatsapp_id IS NULL
  AND contacto.canal_id = conversacion.canal_id
  AND contacto.telefono_normalizado = right(
    regexp_replace(conversacion.telefono_normalizado, '\D', '', 'g'),
    10
  );

CREATE TABLE IF NOT EXISTS etiquetas_chat (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  nombre          text NOT NULL UNIQUE,
  color           text NOT NULL DEFAULT '#64748b',
  creado_en       timestamptz NOT NULL DEFAULT now(),
  actualizado_en  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS conversaciones_etiquetas (
  conversacion_id  uuid NOT NULL REFERENCES conversaciones(id) ON DELETE CASCADE,
  etiqueta_id      uuid NOT NULL REFERENCES etiquetas_chat(id) ON DELETE CASCADE,
  creado_en        timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (conversacion_id, etiqueta_id)
);

INSERT INTO etiquetas_chat (nombre, color) VALUES
  ('bot_off', '#dc2626'),
  ('escalado_humano', '#ea580c'),
  ('recordatorio_enviado', '#2563eb'),
  ('no_asistio', '#7c3aed'),
  ('cita_confirmada', '#16a34a')
ON CONFLICT (nombre) DO NOTHING;

ALTER TABLE mensajes
  ADD COLUMN IF NOT EXISTS numero_compat bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000),
  ADD COLUMN IF NOT EXISTS privado boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS media_ruta text,
  ADD COLUMN IF NOT EXISTS media_mime text,
  ADD COLUMN IF NOT EXISTS media_nombre text,
  ADD COLUMN IF NOT EXISTS media_tamano bigint;

CREATE UNIQUE INDEX IF NOT EXISTS mensajes_numero_compat_key
  ON mensajes(numero_compat);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'mensajes_media_tamano_check'
      AND conrelid = 'mensajes'::regclass
  ) THEN
    ALTER TABLE mensajes
      ADD CONSTRAINT mensajes_media_tamano_check
      CHECK (media_tamano IS NULL OR media_tamano BETWEEN 0 AND 16777216);
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS tokens_integracion (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  nombre          text NOT NULL,
  token_hash      text NOT NULL UNIQUE,
  token_prefijo   text NOT NULL,
  activo          boolean NOT NULL DEFAULT true,
  ultimo_uso_en   timestamptz,
  revocado_en     timestamptz,
  creado_en       timestamptz NOT NULL DEFAULT now(),
  actualizado_en  timestamptz NOT NULL DEFAULT now(),
  CHECK (length(token_hash) = 64)
);

CREATE TABLE IF NOT EXISTS webhooks_integracion (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  nombre            text NOT NULL,
  url               text NOT NULL,
  secreto_cifrado   text,
  eventos           text[] NOT NULL DEFAULT ARRAY[
                      'message_created',
                      'message_updated',
                      'conversation_created',
                      'conversation_status_changed',
                      'conversation_updated',
                      'contact_updated'
                    ]::text[],
  activo            boolean NOT NULL DEFAULT true,
  creado_en         timestamptz NOT NULL DEFAULT now(),
  actualizado_en    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS auditoria_bot (
  id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  token_id            uuid REFERENCES tokens_integracion(id) ON DELETE SET NULL,
  token_fingerprint   text,
  metodo              text NOT NULL,
  ruta                text NOT NULL,
  status_http         integer NOT NULL CHECK (status_http BETWEEN 100 AND 599),
  accion              text NOT NULL,
  conversacion_id     uuid REFERENCES conversaciones(id) ON DELETE SET NULL,
  ip_origen           text,
  detalle             jsonb NOT NULL DEFAULT '{}'::jsonb,
  creado_en           timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS entregas_webhook (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  webhook_id         uuid REFERENCES webhooks_integracion(id) ON DELETE SET NULL,
  mensaje_id         uuid REFERENCES mensajes(id) ON DELETE SET NULL,
  evento             text NOT NULL CHECK (evento IN (
                       'message_created',
                       'message_updated',
                       'conversation_created',
                       'conversation_status_changed',
                       'conversation_updated',
                       'contact_updated'
                     )),
  payload            jsonb NOT NULL,
  estado             text NOT NULL DEFAULT 'pendiente'
                     CHECK (estado IN ('pendiente', 'enviando', 'entregado', 'fallido')),
  intentos           integer NOT NULL DEFAULT 0 CHECK (intentos >= 0),
  proximo_intento_en timestamptz NOT NULL DEFAULT now(),
  ultimo_error       text,
  creado_en          timestamptz NOT NULL DEFAULT now(),
  actualizado_en     timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_contactos_whatsapp_telefono
  ON contactos_whatsapp(telefono_normalizado);
CREATE INDEX IF NOT EXISTS idx_conversaciones_contacto_whatsapp
  ON conversaciones(contacto_whatsapp_id);
CREATE INDEX IF NOT EXISTS idx_auditoria_bot_creado
  ON auditoria_bot(creado_en DESC);
CREATE INDEX IF NOT EXISTS idx_entregas_webhook_pendientes
  ON entregas_webhook(estado, proximo_intento_en)
  WHERE estado IN ('pendiente', 'fallido');

