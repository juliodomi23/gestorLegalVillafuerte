-- Varios números de WhatsApp conectados: cada canal es un inbox con ID numérico propio
-- (la API compatible con Chatwoot lo recibe como inbox_id). Aditivo e idempotente.
BEGIN;

ALTER TABLE canales_whatsapp
  ADD COLUMN IF NOT EXISTS numero_compat bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1);

CREATE UNIQUE INDEX IF NOT EXISTS canales_whatsapp_numero_compat_key
  ON canales_whatsapp(numero_compat);

SELECT setval(
  pg_get_serial_sequence('canales_whatsapp', 'numero_compat'),
  GREATEST(1, COALESCE((SELECT MAX(numero_compat) FROM canales_whatsapp), 1)),
  true
);

COMMIT;
